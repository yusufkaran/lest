// Turns the SVG files in Resources/Phosphor into Sources/Lest/Icons/Phosphor.swift, so the
// icons are compiled into the binary and the app needs no resource bundle.
// Usage: swift scripts/embed-icons.swift   (see `make icons`)
import Foundation

let sourceDirectory = URL(filePath: "Resources/Phosphor", directoryHint: .isDirectory)
let output = URL(filePath: "Sources/Lest/Icons/Phosphor.swift")

/// "check-circle-fill" becomes "checkCircleFill".
func caseName(for fileName: String) -> String {
    let words = fileName.split(separator: "-")
    return words.prefix(1).joined() + words.dropFirst().map(\.capitalized).joined()
}

let names = try FileManager.default.contentsOfDirectory(atPath: sourceDirectory.path(percentEncoded: false))
    .filter { $0.hasSuffix(".svg") }
    .map { String($0.dropLast(".svg".count)) }
    .sorted()

var lines = [
    "// Generated by scripts/embed-icons.swift from Resources/Phosphor. Do not edit by hand:",
    "// add or remove SVG files there and run `make icons`.",
    "//",
    "// Phosphor Icons (https://phosphoricons.com), MIT License. See Resources/Phosphor/LICENSE.",
    "",
    "/// The Phosphor icons the app uses, with their SVG source compiled in.",
    "enum Phosphor: String, CaseIterable {",
]
lines += names.map { "    case \(caseName(for: $0)) = \"\($0)\"" }
lines += ["", "    var svg: String {", "        switch self {"]
for name in names {
    let svg = try String(contentsOf: sourceDirectory.appending(path: "\(name).svg"), encoding: .utf8)
        .trimmingCharacters(in: .whitespacesAndNewlines)
    lines += ["        case .\(caseName(for: name)):", "            #\"\(svg)\"#"]
}
lines += ["        }", "    }", "}", ""]

try FileManager.default.createDirectory(at: output.deletingLastPathComponent(), withIntermediateDirectories: true)
try lines.joined(separator: "\n").write(to: output, atomically: true, encoding: .utf8)
print("\(names.count) icons written to \(output.relativePath)")
