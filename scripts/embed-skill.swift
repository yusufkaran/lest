// Turns skill/lest/SKILL.md into Sources/LestCore/Connections/SkillText.swift, so the skill is
// compiled into the binary and the app can install it without a resource bundle.
// Usage: swift scripts/embed-skill.swift   (see `make skill`)
import Foundation

let source = URL(filePath: "skill/lest/SKILL.md")
let output = URL(filePath: "Sources/LestCore/Connections/SkillText.swift")

let markdown = try String(contentsOf: source, encoding: .utf8)
// The text sits in a raw string, which only its closing quotes could end early.
let closingQuotes = String(repeating: "\"", count: 3) + "#"
precondition(!markdown.contains(closingQuotes), "skill/lest/SKILL.md contains \(closingQuotes)")

let indentation = String(repeating: " ", count: 8)
var lines = [
    "// Generated by scripts/embed-skill.swift from skill/lest/SKILL.md. Do not edit by hand:",
    "// edit that file and run `make skill`.",
    "",
    "/// The skill that tells a coding tool when and how to run `lest`, compiled in so the app",
    "/// can install it.",
    "enum SkillText {",
    "    static let markdown = #\"\"\"",
]
// Splitting on "\n" leaves an empty last element for the file's final newline; written as a
// blank line before the closing quotes, it puts that newline back into the string.
lines += markdown.components(separatedBy: "\n").map { $0.isEmpty ? "" : indentation + $0 }
lines += ["\(indentation)\"\"\"#", "}", ""]

try FileManager.default.createDirectory(at: output.deletingLastPathComponent(), withIntermediateDirectories: true)
try lines.joined(separator: "\n").write(to: output, atomically: true, encoding: .utf8)
print("Skill written to \(output.relativePath)")
